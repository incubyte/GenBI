import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  OneToOne,
  JoinColumn,
} from 'typeorm';
import { DataSource } from './data-source.entity';

@Entity('data_source_schemas')
export class DataSourceSchema {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @OneToOne(() => DataSource, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'data_source_id' })
  dataSource: DataSource;

  @Column()
  dataSourceId: string;

  @Column({ type: 'text' })
  schemaMarkdown: string;

  @Column({ default: false })
  isAutoGenerated: boolean;

  @Column({ nullable: true })
  lastExtracted: Date;

  @CreateDateColumn()
  createdAt: Date;

  @UpdateDateColumn()
  updatedAt: Date;
}
