import { Injectable, Logger } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { Repository } from 'typeorm';
import { DataSource as TypeORMDataSource, Connection } from 'typeorm';
import { DataSource, DataSourceType } from './entities/data-source.entity';
import { DataSourceSchema } from './entities/data-source-schema.entity';
import * as mysql from 'mysql2/promise';
import * as pg from 'pg';
import * as sqlite3 from 'sqlite3';
import { open } from 'sqlite';
import { MongoClient } from 'mongodb';

@Injectable()
export class SchemaExtractionService {
  private readonly logger = new Logger(SchemaExtractionService.name);

  constructor(
    @InjectRepository(DataSource)
    private dataSourceRepository: Repository<DataSource>,
    @InjectRepository(DataSourceSchema)
    private schemaRepository: Repository<DataSourceSchema>,
  ) {}

  /**
   * Get schema for a data source
   */
  async getSchema(dataSourceId: string): Promise<DataSourceSchema | null> {
    return this.schemaRepository.findOne({
      where: { dataSourceId },
    });
  }

  /**
   * Extract schema from a data source and store it as markdown
   */
  async extractAndStoreSchema(dataSourceId: string): Promise<DataSourceSchema> {
    this.logger.log(`Extracting schema for data source ${dataSourceId}`);

    // Get the data source
    const dataSource = await this.dataSourceRepository.findOne({
      where: { id: dataSourceId },
    });

    if (!dataSource) {
      throw new Error(`Data source with ID ${dataSourceId} not found`);
    }

    // Extract schema based on data source type
    let schemaMarkdown: string;

    try {
      switch (dataSource.type) {
        case DataSourceType.POSTGRESQL:
          schemaMarkdown = await this.extractPostgresSchema(dataSource);
          break;
        case DataSourceType.MYSQL:
          schemaMarkdown = await this.extractMySqlSchema(dataSource);
          break;
        case DataSourceType.SQLITE:
          schemaMarkdown = await this.extractSqliteSchema(dataSource);
          break;
        case DataSourceType.MONGODB:
          schemaMarkdown = await this.extractMongoSchema(dataSource);
          break;
        default:
          schemaMarkdown = await this.generateGenericSchema(dataSource);
      }
    } catch (error) {
      this.logger.error(`Error extracting schema: ${error.message}`, error.stack);
      schemaMarkdown = `# Schema Extraction Failed\n\nError: ${error.message}\n\nPlease check your connection details and try again.`;
    }

    // Store the schema
    return this.storeSchema(dataSource, schemaMarkdown);
  }

  /**
   * Store schema in the database
   */
  private async storeSchema(dataSource: DataSource, schemaMarkdown: string): Promise<DataSourceSchema> {
    // Check if schema already exists
    let schema = await this.schemaRepository.findOne({
      where: { dataSourceId: dataSource.id },
    });

    if (schema) {
      // Update existing schema
      schema.schemaMarkdown = schemaMarkdown;
      schema.lastExtracted = new Date();
      schema.isAutoGenerated = true;
    } else {
      // Create new schema
      schema = this.schemaRepository.create({
        dataSource,
        dataSourceId: dataSource.id,
        schemaMarkdown,
        lastExtracted: new Date(),
        isAutoGenerated: true,
      });
    }

    return this.schemaRepository.save(schema);
  }

  /**
   * Extract schema from PostgreSQL database
   */
  private async extractPostgresSchema(dataSource: DataSource): Promise<string> {
    const { host, port, database, username, password, ssl } = dataSource.connectionDetails;

    // Create connection
    const client = new pg.Client({
      host,
      port,
      database,
      user: username,
      password,
      ssl: ssl ? { rejectUnauthorized: false } : false,
    });

    try {
      await client.connect();

      // Get tables
      const tablesResult = await client.query(`
        SELECT
          table_name,
          table_schema
        FROM
          information_schema.tables
        WHERE
          table_schema NOT IN ('pg_catalog', 'information_schema')
          AND table_type = 'BASE TABLE'
        ORDER BY
          table_schema, table_name
      `);

      let markdown = `# PostgreSQL Database Schema: ${database}\n\n`;

      // Process each table
      for (const table of tablesResult.rows) {
        const tableName = table.table_name;
        const schemaName = table.table_schema;
        const fullTableName = `${schemaName}.${tableName}`;

        markdown += `## Table: ${fullTableName}\n\n`;

        // Get columns
        const columnsResult = await client.query(`
          SELECT
            column_name,
            data_type,
            is_nullable,
            column_default,
            character_maximum_length
          FROM
            information_schema.columns
          WHERE
            table_schema = $1 AND table_name = $2
          ORDER BY
            ordinal_position
        `, [schemaName, tableName]);

        markdown += `| Column | Type | Nullable | Default | Description |\n`;
        markdown += `|--------|------|----------|---------|-------------|\n`;

        for (const column of columnsResult.rows) {
          const type = column.data_type + (column.character_maximum_length ? `(${column.character_maximum_length})` : '');
          markdown += `| ${column.column_name} | ${type} | ${column.is_nullable === 'YES' ? 'Yes' : 'No'} | ${column.column_default || ''} | |\n`;
        }

        markdown += '\n';

        // Get primary key
        const pkResult = await client.query(`
          SELECT
            kcu.column_name
          FROM
            information_schema.table_constraints tc
            JOIN information_schema.key_column_usage kcu
              ON tc.constraint_name = kcu.constraint_name
              AND tc.table_schema = kcu.table_schema
          WHERE
            tc.constraint_type = 'PRIMARY KEY'
            AND tc.table_schema = $1
            AND tc.table_name = $2
          ORDER BY
            kcu.ordinal_position
        `, [schemaName, tableName]);

        if (pkResult.rows.length > 0) {
          const pkColumns = pkResult.rows.map(row => row.column_name).join(', ');
          markdown += `**Primary Key:** ${pkColumns}\n\n`;
        }

        // Get foreign keys
        const fkResult = await client.query(`
          SELECT
            kcu.column_name,
            ccu.table_schema AS foreign_table_schema,
            ccu.table_name AS foreign_table_name,
            ccu.column_name AS foreign_column_name
          FROM
            information_schema.table_constraints AS tc
            JOIN information_schema.key_column_usage AS kcu
              ON tc.constraint_name = kcu.constraint_name
              AND tc.table_schema = kcu.table_schema
            JOIN information_schema.constraint_column_usage AS ccu
              ON ccu.constraint_name = tc.constraint_name
              AND ccu.table_schema = tc.table_schema
          WHERE
            tc.constraint_type = 'FOREIGN KEY'
            AND tc.table_schema = $1
            AND tc.table_name = $2
        `, [schemaName, tableName]);

        if (fkResult.rows.length > 0) {
          markdown += `**Foreign Keys:**\n\n`;
          for (const fk of fkResult.rows) {
            markdown += `- ${fk.column_name} -> ${fk.foreign_table_schema}.${fk.foreign_table_name}.${fk.foreign_column_name}\n`;
          }
          markdown += '\n';
        }
      }

      return markdown;
    } finally {
      await client.end();
    }
  }

  /**
   * Extract schema from MySQL database
   */
  private async extractMySqlSchema(dataSource: DataSource): Promise<string> {
    const { host, port, database, username, password } = dataSource.connectionDetails;

    // Create connection
    const connection = await mysql.createConnection({
      host,
      port,
      database,
      user: username,
      password,
    });

    try {
      // Get tables
      const [tables] = await connection.query(`
        SELECT
          table_name
        FROM
          information_schema.tables
        WHERE
          table_schema = ?
          AND table_type = 'BASE TABLE'
        ORDER BY
          table_name
      `, [database]);

      let markdown = `# MySQL Database Schema: ${database}\n\n`;

      // Process each table
      for (const table of tables as any[]) {
        const tableName = table.table_name;

        markdown += `## Table: ${tableName}\n\n`;

        // Get columns
        const [columns] = await connection.query(`
          SELECT
            column_name,
            data_type,
            is_nullable,
            column_default,
            character_maximum_length,
            column_key,
            extra
          FROM
            information_schema.columns
          WHERE
            table_schema = ? AND table_name = ?
          ORDER BY
            ordinal_position
        `, [database, tableName]);

        markdown += `| Column | Type | Nullable | Default | Key | Extra | Description |\n`;
        markdown += `|--------|------|----------|---------|-----|-------|-------------|\n`;

        for (const column of columns as any[]) {
          const type = column.data_type + (column.character_maximum_length ? `(${column.character_maximum_length})` : '');
          markdown += `| ${column.column_name} | ${type} | ${column.is_nullable === 'YES' ? 'Yes' : 'No'} | ${column.column_default || ''} | ${column.column_key || ''} | ${column.extra || ''} | |\n`;
        }

        markdown += '\n';

        // Get foreign keys
        const [fks] = await connection.query(`
          SELECT
            column_name,
            referenced_table_name,
            referenced_column_name
          FROM
            information_schema.key_column_usage
          WHERE
            table_schema = ?
            AND table_name = ?
            AND referenced_table_name IS NOT NULL
        `, [database, tableName]);

        if ((fks as any[]).length > 0) {
          markdown += `**Foreign Keys:**\n\n`;
          for (const fk of fks as any[]) {
            markdown += `- ${fk.column_name} -> ${fk.referenced_table_name}.${fk.referenced_column_name}\n`;
          }
          markdown += '\n';
        }
      }

      return markdown;
    } finally {
      await connection.end();
    }
  }

  /**
   * Extract schema from SQLite database
   */
  private async extractSqliteSchema(dataSource: DataSource): Promise<string> {
    const { path } = dataSource.connectionDetails;

    // Open database
    const db = await open({
      filename: path,
      driver: sqlite3.Database,
    });

    try {
      // Get tables
      const tables = await db.all(`
        SELECT
          name
        FROM
          sqlite_master
        WHERE
          type = 'table'
          AND name NOT LIKE 'sqlite_%'
        ORDER BY
          name
      `);

      let markdown = `# SQLite Database Schema\n\n`;

      // Process each table
      for (const table of tables) {
        const tableName = table.name;

        markdown += `## Table: ${tableName}\n\n`;

        // Get table info
        const tableInfo = await db.all(`PRAGMA table_info(${tableName})`);

        markdown += `| Column | Type | Nullable | Default | Primary Key | Description |\n`;
        markdown += `|--------|------|----------|---------|-------------|-------------|\n`;

        for (const column of tableInfo) {
          markdown += `| ${column.name} | ${column.type} | ${column.notnull === 0 ? 'Yes' : 'No'} | ${column.dflt_value || ''} | ${column.pk === 1 ? 'Yes' : 'No'} | |\n`;
        }

        markdown += '\n';

        // Get foreign keys
        const foreignKeys = await db.all(`PRAGMA foreign_key_list(${tableName})`);

        if (foreignKeys.length > 0) {
          markdown += `**Foreign Keys:**\n\n`;
          for (const fk of foreignKeys) {
            markdown += `- ${fk.from} -> ${fk.table}.${fk.to}\n`;
          }
          markdown += '\n';
        }
      }

      return markdown;
    } finally {
      await db.close();
    }
  }

  /**
   * Extract schema from MongoDB database
   */
  private async extractMongoSchema(dataSource: DataSource): Promise<string> {
    const { uri, database } = dataSource.connectionDetails;

    // Create connection
    const client = new MongoClient(uri);

    try {
      await client.connect();
      const db = client.db(database);

      // Get collections
      const collections = await db.listCollections().toArray();

      let markdown = `# MongoDB Database Schema: ${database}\n\n`;

      // Process each collection
      for (const collection of collections) {
        const collectionName = collection.name;

        markdown += `## Collection: ${collectionName}\n\n`;

        // Sample documents to infer schema
        const sampleDocs = await db.collection(collectionName).find().limit(5).toArray();

        if (sampleDocs.length > 0) {
          markdown += `### Sample Document Structure\n\n`;
          markdown += '```json\n';
          markdown += JSON.stringify(sampleDocs[0], null, 2);
          markdown += '\n```\n\n';

          // Infer schema from sample documents
          const schema = this.inferMongoSchema(sampleDocs);

          markdown += `### Inferred Schema\n\n`;
          markdown += `| Field | Type | Description |\n`;
          markdown += `|-------|------|-------------|\n`;

          for (const [field, type] of Object.entries(schema)) {
            markdown += `| ${field} | ${type} | |\n`;
          }

          markdown += '\n';
        } else {
          markdown += `No documents found in this collection.\n\n`;
        }
      }

      return markdown;
    } finally {
      await client.close();
    }
  }

  /**
   * Infer MongoDB schema from sample documents
   */
  private inferMongoSchema(documents: any[]): Record<string, string> {
    const schema: Record<string, string> = {};

    // Process each document
    for (const doc of documents) {
      // Process each field
      for (const [field, value] of Object.entries(doc)) {
        if (field === '_id') continue;

        let type: string;

        if (value === null) {
          type = 'null';
        } else if (Array.isArray(value)) {
          type = 'array';
        } else if (typeof value === 'object') {
          type = 'object';
        } else {
          type = typeof value;
        }

        // Only add if not already in schema or if current type is different
        if (!schema[field] || schema[field] !== type) {
          schema[field] = type;
        }
      }
    }

    return schema;
  }

  /**
   * Generate a generic schema for other data source types
   */
  private async generateGenericSchema(dataSource: DataSource): Promise<string> {
    // For file-based or API data sources, we'll generate a schema based on the tables and columns in our database
    const dataSourceWithTables = await this.dataSourceRepository.findOne({
      where: { id: dataSource.id },
      relations: ['tables', 'tables.columns'],
    });

    if (!dataSourceWithTables || !dataSourceWithTables.tables) {
      return `# Schema for ${dataSource.name}\n\nNo schema information available.`;
    }

    let markdown = `# Schema for ${dataSource.name}\n\n`;

    // Process each table
    for (const table of dataSourceWithTables.tables) {
      markdown += `## ${table.name}\n\n`;

      if (table.columns && table.columns.length > 0) {
        markdown += `| Column | Type | Primary Key | Nullable | Description |\n`;
        markdown += `|--------|------|-------------|----------|-------------|\n`;

        for (const column of table.columns) {
          markdown += `| ${column.name} | ${column.type} | ${column.isPrimary ? 'Yes' : 'No'} | ${column.isNullable ? 'Yes' : 'No'} | ${column.description || ''} |\n`;
        }

        markdown += '\n';
      } else {
        markdown += `No column information available.\n\n`;
      }
    }

    return markdown;
  }
}
